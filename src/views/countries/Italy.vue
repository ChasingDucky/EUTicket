      <p><strong>Booking Timeline:</strong></p>
      <ol>
        <li><strong>4-6 months ahead:</strong> Tickets released, best Low Cost availability</li>
        <li><strong>2-3 months ahead:</strong> Good selection, competitive prices</li>
        <li><strong>1 month ahead:</strong> Limited Low Cost, book now or risk higher prices</li>
        <li><strong>1-2 weeks ahead:</strong> Prices increasing rapidly</li>
        <li><strong>Last minute (1-3 days):</strong> Expect 2-3x higher prices</li>
      </ol>

      <p><strong>Best Times to Travel (Cheapest):</strong></p>
      <ul>
        <li>Mid-morning: 10:00-12:00</li>
        <li>Mid-afternoon: 14:00-16:00</li>
        <li>Tuesday-Thursday (avoid Friday/Sunday)</li>
      </ul>

      <p><strong>Most Expensive Times:</strong></p>
      <ul>
        <li>Early morning: 06:00-08:00 (business travelers)</li>
        <li>Evening: 17:00-20:00 (commuters returning)</li>
        <li>Friday evening (weekend travelers)</li>
        <li>Sunday afternoon/evening (returning from weekend)</li>
      </ul>

