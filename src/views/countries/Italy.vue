    <h1>🇮🇹 Italy Railway Travel Guide</h1>

    <h2>Overview</h2>
    <p>Italy's railway network is one of the most scenic and efficient in Europe, connecting historic cities, coastal towns, and mountain villages. With two competing high-speed operators (Trenitalia and Italo), travelers enjoy competitive prices and frequent services on major routes. From the Frecciarossa speeding between Rome and Milan to regional trains winding through Tuscany, Italian trains offer an unforgettable way to explore the country.</p>

    <div class="info-box">
      <h4>📊 Quick Facts</h4>
      <ul>
        <li><strong>Rail Network:</strong> 16,800+ km of track</li>
        <li><strong>Annual Passengers:</strong> 600+ million</li>
        <li><strong>Stations:</strong> 2,200+ stations nationwide</li>
        <li><strong>High-Speed Network:</strong> 1,450+ km (expanding)</li>
        <li><strong>Top Speed:</strong> 300 km/h (Frecciarossa 1000)</li>
        <li><strong>Operators:</strong> Trenitalia (state) + Italo (private)</li>
      </ul>
    </div>

