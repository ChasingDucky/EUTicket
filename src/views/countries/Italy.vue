      </ul>
    </div>

    <h3>Frecciargento (Silver Arrow) - High-Speed on Classic Lines</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 250 km/h</li>
      <li><strong>Routes:</strong> Rome-Verona-Venice, Rome-Bari/Lecce, Rome-Genoa</li>
      <li><strong>Use Case:</strong> High-speed service on partially upgraded tracks</li>
      <li><strong>Amenities:</strong> Similar to Frecciarossa but slightly older trains</li>
      <li><strong>Classes:</strong> 1st and 2nd class</li>
    </ul>

    <h3>Frecciabianca (White Arrow) - Fast Regional</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 200 km/h</li>
      <li><strong>Routes:</strong> Milan-Venice, Milan-Genoa-Rome, Venice-Trieste</li>
      <li><strong>Use Case:</strong> Fast connections on non-high-speed lines</li>
      <li><strong>Amenities:</strong> Basic but comfortable, some with dining car</li>
      <li><strong>Cheaper than Freccia trains</strong></li>
    </ul>

    <h3>InterCity (IC) - Long-Distance</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 160 km/h</li>
      <li><strong>Routes:</strong> Connects cities not on high-speed network</li>
      <li><strong>Frequency:</strong> Several times daily on most routes</li>
      <li><strong>Reservation:</strong> Recommended but not always mandatory</li>
      <li><strong>Cost:</strong> 30-50% cheaper than Freccia trains</li>
    </ul>

    <h3>Regionale (R) & Regionale Veloce (RV)</h3>
    <ul>
      <li><strong>Speed:</strong> 80-120 km/h</li>
      <li><strong>Coverage:</strong> Local and regional routes, all stations</li>
      <li><strong>No Reservation:</strong> First-come, first-served seating</li>
      <li><strong>Cost:</strong> Very affordable (€5-15 for most journeys)</li>
      <li><strong>Perfect for:</strong> Tuscan countryside, Cinque Terre, local exploration</li>
      <li><strong>Must Validate:</strong> Stamp ticket at yellow machines before boarding!</li>
    </ul>

