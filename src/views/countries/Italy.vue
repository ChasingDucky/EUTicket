    <h2>FAQs - Italy Rail Travel</h2>

    <details>
      <summary><strong>Do I need to book trains in advance in Italy?</strong></summary>
      <p><strong>High-speed trains (Freccia/Italo):</strong> YES, highly recommended! Prices increase as trains fill up, and popular routes sell out.<br><strong>Regional trains:</strong> NO, buy at station same day. They don't sell out and no advance discount.</p>
    </details>

    <details>
      <summary><strong>Which is better: Trenitalia or Italo?</strong></summary>
      <p>Both are excellent! <strong>Italo</strong> is often 10-20% cheaper and has newer trains, but runs fewer routes. <strong>Trenitalia</strong> has more comprehensive coverage including regional trains. Always compare both when booking high-speed routes.</p>
    </details>

    <details>
      <summary><strong>Why must I validate regional tickets?</strong></summary>
      <p>Regional tickets are "open" - valid for any train on that route within 6 hours. Validation stamps date/time to prevent reuse. If inspectors find an unvalidated ticket, it's a €50+ fine even if you just bought it. Yellow/green machines on platforms - don't forget!</p>
    </details>

    <details>
      <summary><strong>Can I get a refund if I miss my train?</strong></summary>
      <p>Depends on ticket type:<ul><li><strong>Low Cost/Base:</strong> No refund, ticket lost</li><li><strong>Economy:</strong> Partial refund possible with fee</li><li><strong>Flex:</strong> Can change to later train for free</li></ul>If YOU are late (not the train's fault), you usually can't use the ticket on a later train unless you have a Flex ticket.</p>
    </details>

    <details>
      <summary><strong>Is CartaFRECCIA worth it for tourists?</strong></summary>
      <p>YES, it's FREE! Sign up takes 2 minutes, and you earn points on every journey. Even if you only make 2-3 trips, you'll earn €5-10 in points for future travel. Plus you get access to member-only promotions. No downside!</p>
    </details>

    <details>
      <summary><strong>How early should I arrive at the station?</strong></summary>
      <p><ul><li><strong>High-speed trains:</strong> 15-20 minutes (30 min for Roma Termini)</li><li><strong>Regional trains:</strong> 5-10 minutes</li><li><strong>First time at station:</strong> Add 10-15 minutes to find platform</li></ul>Platform numbers often appear 10-20 min before departure, so don't arrive too early either!</p>
    </details>

