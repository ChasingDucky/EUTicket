      <ul>
        <li><strong>Fixed travel dates, booking ahead?</strong> → Compare Low Cost fares from both operators</li>
        <li><strong>Slight flexibility with times?</strong> → Check prices for trains 1-2 hours before/after</li>
        <li><strong>Uncertain schedule?</strong> → Economy or Flex fare</li>
        <li><strong>Under 26 or over 60?</strong> → Buy Carta Verde/Argento FIRST, then book with discount</li>
        <li><strong>Making 3+ trips?</strong> → Sign up for CartaFRECCIA/Italo Più loyalty programs</li>
