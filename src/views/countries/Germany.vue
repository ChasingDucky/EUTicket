    <h2>FAQs - Germany Rail Travel</h2>

    <details>
      <summary><strong>Can I use €49 ticket on ICE trains?</strong></summary>
      <p>No, the €49 Deutschland-Ticket is only valid on regional trains (RE, RB, IRE) and local transport (S-Bahn, U-Bahn, trams, buses). It's NOT valid on ICE, IC, or EC long-distance trains.</p>
    </details>

    <details>
      <summary><strong>Do I need to reserve seats in advance?</strong></summary>
      <p>Seat reservations are optional on German trains (€4.90) but highly recommended for:<ul><li>Friday evenings and Sunday afternoons</li><li>Holiday periods</li><li>Long-distance journeys (3+ hours)</li><li>Traveling with groups</li></ul>Without a reservation, you can sit in any unreserved seat.</p>
    </details>

    <details>
      <summary><strong>What if my train is cancelled or I miss my connection?</strong></summary>
      <p>With Flexpreis tickets, you can take any other train on the same route. With Sparpreis, if delay/cancellation is DB's fault (not your fault for being late), you can take the next available train. Use DB Navigator app to report disruption immediately.</p>
    </details>

    <details>
      <summary><strong>Can I get a refund if I change my mind?</strong></summary>
      <p>Depends on ticket type:<ul><li><strong>Flexpreis:</strong> Full refund if cancelled before day before travel</li><li><strong>Sparpreis:</strong> Partial refund minus €10 cancellation fee</li><li><strong>Super Sparpreis:</strong> No refund</li></ul></p>
    </details>

    <details>
      <summary><strong>Is the BahnCard worth it for tourists?</strong></summary>
      <p>For short visits (1-2 weeks), probably not. But if making 3+ long-distance trips, BahnCard 25 (€55.50) pays for itself. Calculate: if you'd spend €222+ on tickets, BahnCard 25 saves money. The first-year trial (€27.75) makes it easier to break even.</p>
    </details>

