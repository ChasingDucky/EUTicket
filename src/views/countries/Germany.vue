    <h2>Types of Trains - Complete Guide</h2>

    <h3>ICE (InterCity Express) - High-Speed Trains</h3>
    <div class="info-box">
      <ul>
        <li><strong>Speed:</strong> Up to 300 km/h (186 mph)</li>
        <li><strong>Routes:</strong> Major cities across Germany + international destinations</li>
        <li><strong>Classes:</strong> 1st class (premium) and 2nd class (standard)</li>
        <li><strong>Amenities:</strong>
          <ul>
            <li>Free WiFi (can be slow during peak times)</li>
            <li>Power outlets at every seat (230V European plugs)</li>
            <li>Bistro/restaurant car with hot meals</li>
            <li>Air conditioning and spacious seating</li>
            <li>Quiet zones (Ruhebereich)</li>
            <li>Family compartments with play areas</li>
            <li>Wheelchair accessible with dedicated spaces</li>
          </ul>
        </li>
        <li><strong>Reservation:</strong> Optional but recommended (€4.90 per seat)</li>
        <li><strong>Ticket Types:</strong> All fare types accepted (Sparpreis, Flexpreis, BahnCard)</li>
      </ul>
    </div>

    <h3>IC/EC (InterCity/EuroCity)</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 200 km/h</li>
      <li><strong>Use Case:</strong> Long-distance connections on non-high-speed routes</li>
      <li><strong>Amenities:</strong> Similar to ICE but older trains, bistro car available</li>
      <li><strong>EC Trains:</strong> International connections to neighboring countries</li>
      <li><strong>Cost:</strong> Usually same price as ICE for same route</li>
    </ul>

    <h3>RE (Regional Express)</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 160 km/h</li>
      <li><strong>Stops:</strong> Major regional stations, skips smaller stops</li>
      <li><strong>Range:</strong> 50-200 km routes</li>
      <li><strong>Amenities:</strong> Basic seating, usually no bistro car</li>
      <li><strong>No Reservation:</strong> Seat yourself, first-come-first-served</li>
      <li><strong>Deutschland-Ticket Valid:</strong> ✅ Yes</li>
    </ul>

    <h3>RB (RegionalBahn)</h3>
    <ul>
      <li><strong>Speed:</strong> Up to 120 km/h</li>
      <li><strong>Stops:</strong> All stations including small villages</li>
      <li><strong>Use Case:</strong> Local travel, exploring countryside</li>
      <li><strong>Frequency:</strong> Every 30-60 minutes on most routes</li>
      <li><strong>Deutschland-Ticket Valid:</strong> ✅ Yes</li>
    </ul>

    <h3>S-Bahn (Suburban Railway)</h3>
    <ul>
      <li><strong>Coverage:</strong> Metropolitan areas (Berlin, Munich, Hamburg, etc.)</li>
      <li><strong>Frequency:</strong> Every 5-20 minutes</li>
      <li><strong>Zones:</strong> Fare zones based on distance from city center</li>
      <li><strong>Integration:</strong> Often integrated with metro/bus tickets</li>
      <li><strong>Deutschland-Ticket Valid:</strong> ✅ Yes (all zones)</li>
    </ul>

