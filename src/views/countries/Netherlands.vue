    <h2>The OV-chipkaart System</h2>

    <p>The OV-chipkaart is the primary payment method for ALL public transport in the Netherlands (trains, trams, buses, metro). There are three types:</p>

    <h3>1. Anonymous OV-chipkaart (For Tourists) 🏆</h3>
    <div class="info-box tip">
      <p><strong>Cost:</strong> €7.50 (one-time card purchase)</p>
      <p><strong>Validity:</strong> 5 years</p>
      <p><strong>How it Works:</strong></p>
      <ul>
        <li>Buy at ticket machines, NS ticket offices, or many shops</li>
        <li>Load credit onto the card (minimum €20 for trains)</li>
        <li>Check in when boarding, check out when exiting</li>
        <li>Fare automatically deducted based on distance traveled</li>
        <li>Works on trains, trams, buses, metro across entire country</li>
      </ul>
      <p><strong>Minimum Balance for Trains:</strong> €20 (€10 for other transport)</p>
      <p><strong>Refundable:</strong> Card can be returned for €7.50 refund minus any remaining credit</p>
    </div>

    <h3>2. Personal OV-chipkaart</h3>
    <ul>
      <li><strong>Cost:</strong> €7.50</li>
      <li><strong>Requires:</strong> Dutch address, takes 5-7 days to receive</li>
      <li><strong>Benefits:</strong> Can add NS Flex subscriptions, automatic travel history</li>
      <li><strong>For Tourists:</strong> Not practical unless staying long-term</li>
    </ul>

    <h3>3. Single-Use Paper Tickets</h3>
    <ul>
      <li><strong>When:</strong> If you don't have OV-chipkaart</li>
      <li><strong>Cost:</strong> €1 extra surcharge per ticket</li>
      <li><strong>Convenience:</strong> Less flexible than OV-chipkaart</li>
      <li><strong>Not Recommended:</strong> OV-chipkaart is much better value</li>
    </ul>

